#!/usr/bin/env python3
"""A simple GUI to set up new DRCM clusters and migrate existing ones.

Two tabs:
  * New cluster  -- fill in cluster-wide settings and a list of nodes, then
                    generate a ready-to-edit cm.cfg (UDP or TCP + TLS, with
                    anti-replay and witness-quorum options).
  * Migrate      -- load a pre-Phase-4 cm.cfg and write the new-format file,
                    optionally switching it to the TCP + TLS transport.

The GUI uses only the Python standard library (tkinter). The configuration
is produced by generate_config(), a pure function kept separate from the
widgets so it can be tested headless. The migrate tab reuses migrate_cfg.py.
"""
import os
import sys

# Pure config generation (no tkinter) so it can be imported and tested
# without a display.

def _csv(items):
    return ", ".join(x for x in items if x)


def generate_config(s):
    """Build a cm.cfg string from a settings dict.

    s keys:
      udpport, tcpport, dead_node_count, run_dir, log_dir, spool_dir,
      cluster_user, cluster_group, logfile, debug_level,
      transport ('udp'|'tcp'), tls_ca, tls_cert, tls_key, tls_min,
      replay_window_secs, quorum_required (bool), witness_endpoint,
      services  -> list of (nickname, service_name, resource_script)
      nodes     -> list of dicts: nodename, hostname, keep_alive_ip,
                   services (list of nicknames), peer_endpoints (str),
                   tls_peer_fingerprint (str)
    """
    L = []
    a = L.append
    a("# DR Cluster Manager configuration (generated by drcm_gui.py)")
    a("")
    a("[CM_SERVER]")
    a("udpport = %s" % s.get("udpport", 53897))
    a("tcpport = %s" % s.get("tcpport", 53898))
    a("dead_node_count = %s" % s.get("dead_node_count", 3))
    a("run_dir = %s" % s.get("run_dir", "/var/run/drcm"))
    a("log_dir = %s" % s.get("log_dir", "/var/log/drcm"))
    a("spool_dir = %s" % s.get("spool_dir", "/var/spool/drcm"))
    a("cluster_user = %s" % s.get("cluster_user", "root"))
    a("cluster_group = %s" % s.get("cluster_group", "root"))
    a("logfile = %s" % s.get("logfile", "drcm.log"))
    a("debug = 1")
    a("debug_level = %s" % s.get("debug_level", 1))
    a("")
    a("# ---- Phase 4: transport / TLS / anti-replay / quorum ----")
    transport = s.get("transport", "udp")
    a("cluster_transport = %s" % transport)
    if transport == "tcp":
        a("tls_ca_file = %s" % s.get("tls_ca", "/etc/drcm/tls/ca.pem"))
        a("tls_cert_file = %s" % s.get("tls_cert", "/etc/drcm/tls/node.pem"))
        a("tls_key_file = %s" % s.get("tls_key", "/etc/drcm/tls/node-key.pem"))
        a("tls_min_version = %s" % s.get("tls_min", "1.2"))
    a("replay_window_secs = %s" % s.get("replay_window_secs", 0))
    a("quorum_required = %d" % (1 if s.get("quorum_required") else 0))
    if s.get("witness_endpoint"):
        a("witness_endpoint = %s" % s["witness_endpoint"])
    a("")
    services = s.get("services", [])
    if services:
        a("[CM_SERVICES]")
        for nick, svc, script in services:
            a("%s, %s, %s" % (nick, svc, script))
        a("")
    for node in s.get("nodes", []):
        a("[CM_NODE]")
        a("nodename = %s" % node.get("nodename", ""))
        a("hostname = %s" % node.get("hostname", ""))
        a("node_is_active = 1")
        a("keep_alive_ip = %s" % node.get("keep_alive_ip", ""))
        if node.get("peer_endpoints"):
            a("peer_endpoints = %s" % node["peer_endpoints"])
        if node.get("tls_peer_fingerprint"):
            a("tls_peer_fingerprint = %s" % node["tls_peer_fingerprint"])
        a("node_services = %s" % _csv(node.get("services", [])))
        a("")
    a("# End of configuration file")
    return "\n".join(L) + "\n"


# --------------------------------------------------------------------------- #
# GUI. Imported lazily so this module can be used headless (generate_config
# and the migrate helper work without tkinter / a display).
# --------------------------------------------------------------------------- #

def run_gui():
    import tkinter as tk
    from tkinter import ttk, filedialog, messagebox

    sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
    import migrate_cfg  # reused for the Migrate tab

    root = tk.Tk()
    root.title("DRCM Cluster Setup")
    nb = ttk.Notebook(root)
    nb.pack(fill="both", expand=True, padx=8, pady=8)

    # ---- New cluster tab ---------------------------------------------------
    newf = ttk.Frame(nb)
    nb.add(newf, text="New cluster")

    fields = {}
    def row(parent, label, default, r):
        ttk.Label(parent, text=label).grid(row=r, column=0, sticky="w", pady=2)
        v = tk.StringVar(value=str(default))
        ttk.Entry(parent, textvariable=v, width=40).grid(row=r, column=1, sticky="we", pady=2)
        fields[label] = v
        return v

    r = 0
    for lbl, dflt in (("logfile", "drcm.log"), ("udpport", "53897"),
                      ("tcpport", "53898"), ("dead_node_count", "3"),
                      ("witness_endpoint", ""), ("replay_window_secs", "0")):
        row(newf, lbl, dflt, r); r += 1

    transport_var = tk.StringVar(value="udp")
    ttk.Label(newf, text="transport").grid(row=r, column=0, sticky="w")
    ttk.Combobox(newf, textvariable=transport_var, values=["udp", "tcp"],
                 width=10, state="readonly").grid(row=r, column=1, sticky="w"); r += 1
    quorum_var = tk.BooleanVar(value=False)
    ttk.Checkbutton(newf, text="require witness quorum", variable=quorum_var).grid(
        row=r, column=1, sticky="w"); r += 1

    ttk.Label(newf, text="Nodes (one per line: name,hostname,keep_alive_ip,services)").grid(
        row=r, column=0, columnspan=2, sticky="w", pady=(8, 0)); r += 1
    nodes_text = tk.Text(newf, height=6, width=60)
    nodes_text.grid(row=r, column=0, columnspan=2, sticky="we")
    nodes_text.insert("1.0", "n1,node1.example.com,10.0.0.11,web\n"
                             "n2,node2.example.com,10.0.0.12,web\n")
    r += 1
    ttk.Label(newf, text="Services (one per line: nickname,service,script)").grid(
        row=r, column=0, columnspan=2, sticky="w", pady=(8, 0)); r += 1
    svc_text = tk.Text(newf, height=3, width=60)
    svc_text.grid(row=r, column=0, columnspan=2, sticky="we")
    svc_text.insert("1.0", "web, httpd, /etc/drcm/resources/service.sh\n")
    r += 1

    def do_generate():
        nodes = []
        for line in nodes_text.get("1.0", "end").strip().splitlines():
            parts = [p.strip() for p in line.split(",")]
            if len(parts) < 3 or not parts[0]:
                continue
            svcs = [x for x in parts[3:] if x]
            nodes.append(dict(nodename=parts[0], hostname=parts[1],
                              keep_alive_ip=parts[2], services=svcs))
        services = []
        for line in svc_text.get("1.0", "end").strip().splitlines():
            parts = [p.strip() for p in line.split(",")]
            if len(parts) == 3 and parts[0]:
                services.append((parts[0], parts[1], parts[2]))
        s = dict(
            logfile=fields["logfile"].get(), udpport=fields["udpport"].get(),
            tcpport=fields["tcpport"].get(),
            dead_node_count=fields["dead_node_count"].get(),
            witness_endpoint=fields["witness_endpoint"].get().strip(),
            replay_window_secs=fields["replay_window_secs"].get(),
            transport=transport_var.get(), quorum_required=quorum_var.get(),
            nodes=nodes, services=services,
        )
        cfg = generate_config(s)
        path = filedialog.asksaveasfilename(defaultextension=".cfg",
                                            initialfile="cm.cfg",
                                            title="Save new cluster config")
        if not path:
            return
        try:
            with open(path, "w") as f:
                f.write(cfg)
            messagebox.showinfo("DRCM", "Wrote %s" % path)
        except OSError as e:
            messagebox.showerror("DRCM", "Could not write file:\n%s" % e)

    ttk.Button(newf, text="Generate config...", command=do_generate).grid(
        row=r, column=0, columnspan=2, pady=10)
    newf.columnconfigure(1, weight=1)

    # ---- Migrate tab -------------------------------------------------------
    migf = ttk.Frame(nb)
    nb.add(migf, text="Migrate existing")

    mvars = {}
    old_var = tk.StringVar()
    ttk.Label(migf, text="Old cm.cfg").grid(row=0, column=0, sticky="w", pady=2)
    ttk.Entry(migf, textvariable=old_var, width=40).grid(row=0, column=1, sticky="we")
    def pick_old():
        p = filedialog.askopenfilename(title="Select existing cm.cfg")
        if p:
            old_var.set(p)
    ttk.Button(migf, text="Browse...", command=pick_old).grid(row=0, column=2)

    mig_tcp = tk.BooleanVar(value=False)
    ttk.Checkbutton(migf, text="switch to TCP + TLS", variable=mig_tcp).grid(
        row=1, column=1, sticky="w")
    mig_quorum = tk.BooleanVar(value=False)
    ttk.Checkbutton(migf, text="require witness quorum", variable=mig_quorum).grid(
        row=2, column=1, sticky="w")
    mwit = tk.StringVar()
    ttk.Label(migf, text="witness HOST[:PORT]").grid(row=3, column=0, sticky="w")
    ttk.Entry(migf, textvariable=mwit, width=40).grid(row=3, column=1, sticky="we")

    def do_migrate():
        old = old_var.get().strip()
        if not old:
            messagebox.showerror("DRCM", "Pick an existing cm.cfg first")
            return
        try:
            with open(old) as f:
                text = f.read()
        except OSError as e:
            messagebox.showerror("DRCM", "Cannot read:\n%s" % e)
            return
        ns = migrate_cfg.parse_args([old])
        ns.tcp = mig_tcp.get()
        ns.quorum = mig_quorum.get()
        ns.witness = mwit.get().strip()
        out = migrate_cfg.migrate(text, ns)
        path = filedialog.asksaveasfilename(defaultextension=".cfg",
                                            initialfile="cm.new.cfg",
                                            title="Save migrated config")
        if not path:
            return
        try:
            with open(path, "w") as f:
                f.write(out)
            messagebox.showinfo("DRCM", "Wrote migrated config to %s" % path)
        except OSError as e:
            messagebox.showerror("DRCM", "Could not write file:\n%s" % e)

    ttk.Button(migf, text="Migrate...", command=do_migrate).grid(
        row=4, column=1, pady=10, sticky="w")
    migf.columnconfigure(1, weight=1)

    root.mainloop()


if __name__ == "__main__":
    # --selftest exercises generate_config() without a display.
    if "--selftest" in sys.argv:
        cfg = generate_config(dict(
            transport="tcp", quorum_required=True, witness_endpoint="10.0.0.9",
            services=[("web", "httpd", "/etc/drcm/resources/service.sh")],
            nodes=[dict(nodename="n1", hostname="a", keep_alive_ip="10.0.0.11", services=["web"]),
                   dict(nodename="n2", hostname="b", keep_alive_ip="10.0.0.12", services=["web"])],
        ))
        sys.stdout.write(cfg)
        sys.exit(0)
    try:
        run_gui()
    except Exception as e:  # no display, tkinter missing, etc.
        sys.stderr.write("Could not start the GUI (%s).\n" % e)
        sys.stderr.write("This tool needs a graphical display and Python tkinter.\n")
        sys.stderr.write("Run with --selftest to generate a sample config on the console.\n")
        sys.exit(1)
